/**
 * Helper to get image data with safe fallback
 */
export function getProductImageData(productId, fallbackTitle = "Farm Harvest Produce") {
  const data = PRODUCT_IMAGE_MAP[productId];
  if (data && data.url) {
    return data;
  }
  return {
    url: "/images/photographs/farmer-harvest.jpg",
    alt: fallbackTitle,
    credit: "Ulavan Santhai Producer Network",
    gallery: [
      "/images/photographs/farmer-harvest.jpg",
      "/images/photographs/produce-warehouse.jpg",
      "/images/photographs/wholesale-market.jpg",
    ],
  };
}

